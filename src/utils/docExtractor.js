import zlib from 'node:zlib';
import mammoth from 'mammoth';

/**
 * Decode common XML entities in extracted Word text.
 * @param {string} str
 * @returns {string}
 */
function decodeXmlEntities(str) {
  return String(str || '')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&#(\d+);/g, (_, dec) => String.fromCharCode(Number(dec)))
    .replace(/&#x([0-9a-fA-F]+);/g, (_, hex) => String.fromCharCode(parseInt(hex, 16)));
}

/**
 * Escape HTML special characters for safe rendering.
 * @param {string} text
 * @returns {string}
 */
function escapeHtml(text) {
  return String(text || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * Sanitize HTML generated by mammoth to ensure no executable script/event attributes exist
 * while preserving rich Word formatting tags (h1-h6, p, strong, em, u, table, tr, th, td, ul, ol, li, br, span, div).
 * @param {string} rawHtml
 * @returns {string}
 */
export function sanitizeWordHtml(rawHtml) {
  let clean = String(rawHtml || '')
    .replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, '')
    .replace(/<iframe\b[^<]*(?:(?!<\/iframe>)<[^<]*)*<\/iframe>/gi, '')
    .replace(/\son[a-z]+\s*=\s*(?:"[^"]*"|'[^']*'|[^\s>]+)/gi, '')
    .replace(/javascript\s*:/gi, '');

  // Enhance standard Vietnamese administrative headings with semantic styling classes
  clean = clean
    .replace(
      /<p>(?:<strong>)?(CỘNG HÒA XÃ HỘI CHỦ NGHĨA VIỆT NAM)(?:<\/strong>)?<\/p>/gi,
      '<p class="word-quoc-hieu"><strong>$1</strong></p>'
    )
    .replace(
      /<p>(?:<strong>|<em>)*(Độc lập\s*[-–—]\s*Tự do\s*[-–—]\s*Hạnh phúc)(?:<\/em>|<\/strong>)*<\/p>/gi,
      '<p class="word-tieu-ngu"><strong>$1</strong></p>'
    );

  return clean.trim();
}

/**
 * Convert plain text lines into a clean formatted document HTML view when the source is `.txt` or `.doc`.
 * @param {string} plainText
 * @returns {string}
 */
export function convertPlainTextToFormattedHtml(plainText) {
  const lines = String(plainText || '')
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter(Boolean);

  if (lines.length === 0) return '';

  const htmlParts = [];
  const numberedRows = [];

  const flushTableIfAny = () => {
    if (numberedRows.length === 0) return;
    const rowsHtml = numberedRows
      .map((item) => {
        const parts = item.split(/\s+[-–•]\s+/);
        if (parts.length >= 3) {
          const sttAndName = parts[0].replace(/^\d+\.\s*/, '');
          const sttMatch = parts[0].match(/^(\d+)\./);
          const stt = sttMatch ? sttMatch[1] : '';
          return `<tr>
            <td class="col-center">${escapeHtml(stt)}</td>
            <td><strong>${escapeHtml(sttAndName)}</strong></td>
            <td>${escapeHtml(parts[1])}</td>
            <td>${escapeHtml(parts.slice(2).join(' - '))}</td>
          </tr>`;
        }
        return `<tr><td colspan="4">${escapeHtml(item)}</td></tr>`;
      })
      .join('');

    htmlParts.push(`
      <table class="word-doc-table">
        <thead>
          <tr>
            <th class="col-center">STT</th>
            <th>Họ và tên / Hạng mục</th>
            <th>Mã số / Thông tin</th>
            <th>Chi tiết / Kết quả</th>
          </tr>
        </thead>
        <tbody>${rowsHtml}</tbody>
      </table>
    `);
    numberedRows.length = 0;
  };

  for (const line of lines) {
    if (/^\d+\.\s+.+\s+[-–]\s+.+/.test(line)) {
      numberedRows.push(line);
      continue;
    }
    flushTableIfAny();

    if (/^(BỘ GIÁO DỤC|TRƯỜNG ĐẠI HỌC|CỘNG HÒA XÃ HỘI)/i.test(line)) {
      htmlParts.push(`<p class="word-org-header"><strong>${escapeHtml(line)}</strong></p>`);
    } else if (/^(PHÒNG |SỐ HIỆU:|Độc lập)/i.test(line)) {
      htmlParts.push(`<p class="word-sub-header">${escapeHtml(line)}</p>`);
    } else if (/^(QUYẾT ĐỊNH|HỢP ĐỒNG|THÔNG BÁO|BẢNG ĐIỂM)/i.test(line)) {
      htmlParts.push(`<h1 class="word-doc-heading">${escapeHtml(line)}</h1>`);
    } else {
      htmlParts.push(`<p>${escapeHtml(line)}</p>`);
    }
  }
  flushTableIfAny();

  return htmlParts.join('\n');
}

/**
 * Extract entries from a ZIP buffer (supports Stored method=0 and Deflate method=8).
 * Used as a fast synchronous helper alongside `mammoth`.
 * @param {Buffer} zipBuffer
 * @returns {Map<string, Buffer>}
 */
export function parseZipEntries(zipBuffer) {
  const entries = new Map();
  if (!Buffer.isBuffer(zipBuffer) || zipBuffer.length < 22) {
    return entries;
  }

  let eocdOffset = -1;
  const minEocdSearch = Math.max(0, zipBuffer.length - 65557);
  for (let i = zipBuffer.length - 22; i >= minEocdSearch; i -= 1) {
    if (zipBuffer.readUInt32LE(i) === 0x06054b50) {
      eocdOffset = i;
      break;
    }
  }

  if (eocdOffset !== -1) {
    const totalEntries = zipBuffer.readUInt16LE(eocdOffset + 10);
    const centralDirOffset = zipBuffer.readUInt32LE(eocdOffset + 16);
    let ptr = centralDirOffset;

    for (let idx = 0; idx < totalEntries && ptr + 46 <= zipBuffer.length; idx += 1) {
      const sig = zipBuffer.readUInt32LE(ptr);
      if (sig !== 0x02014b50) break;

      const compressionMethod = zipBuffer.readUInt16LE(ptr + 10);
      const compressedSize = zipBuffer.readUInt32LE(ptr + 20);
      const fileNameLen = zipBuffer.readUInt16LE(ptr + 28);
      const extraLen = zipBuffer.readUInt16LE(ptr + 30);
      const commentLen = zipBuffer.readUInt16LE(ptr + 32);
      const localHeaderOffset = zipBuffer.readUInt32LE(ptr + 42);

      const entryName = zipBuffer
        .subarray(ptr + 46, ptr + 46 + fileNameLen)
        .toString('utf8');

      ptr += 46 + fileNameLen + extraLen + commentLen;

      if (localHeaderOffset + 30 <= zipBuffer.length) {
        const localSig = zipBuffer.readUInt32LE(localHeaderOffset);
        if (localSig === 0x04034b50) {
          const localNameLen = zipBuffer.readUInt16LE(localHeaderOffset + 26);
          const localExtraLen = zipBuffer.readUInt16LE(localHeaderOffset + 28);
          const dataStart = localHeaderOffset + 30 + localNameLen + localExtraLen;
          const dataEnd = dataStart + compressedSize;
          if (dataEnd <= zipBuffer.length) {
            const rawSlice = zipBuffer.subarray(dataStart, dataEnd);
            try {
              if (compressionMethod === 0) {
                entries.set(entryName, Buffer.from(rawSlice));
              } else if (compressionMethod === 8) {
                entries.set(entryName, zlib.inflateRawSync(rawSlice));
              }
            } catch {
              // Ignore malformed entry
            }
          }
        }
      }
    }
    return entries;
  }

  return entries;
}

/**
 * Convert WordprocessingML (`word/document.xml`) into clean plain text preserving paragraphs.
 * @param {string} xmlString
 * @returns {string}
 */
export function extractTextFromWordXml(xmlString) {
  const xml = String(xmlString || '');
  if (!xml) return '';

  const withFormatting = xml
    .replace(/<w:tab\b[^>]*\/?>/gi, '\t')
    .replace(/<w:(?:br|cr)\b[^>]*\/?>/gi, '\n')
    .replace(/<\/w:p>/gi, '\n')
    .replace(/<\/w:tr>/gi, '\n')
    .replace(/<\/w:tc>/gi, '\t')
    .replace(/<[^>]+>/g, '');

  return decodeXmlEntities(withFormatting)
    .split(/\r?\n/)
    .map((line) => line.trimEnd())
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/**
 * Convert WordprocessingML (`word/document.xml`) directly into structured semantic HTML
 * (supporting headings, centered lines, bold/italic runs, and `<w:tbl>` tables).
 * Used both as a synchronous renderer and in tandem with `mammoth.convertToHtml`.
 * @param {string} xmlString
 * @returns {string}
 */
export function convertWordXmlToHtml(xmlString) {
  const xml = String(xmlString || '');
  if (!xml) return '';

  const bodyMatch = xml.match(/<w:body[^>]*>([\s\S]*?)<\/w:body>/i);
  const bodyContent = bodyMatch ? bodyMatch[1] : xml;

  // Match top-level <w:p>...</w:p> or <w:tbl>...</w:tbl> blocks
  const blockRegex = /<w:tbl\b[^>]*>[\s\S]*?<\/w:tbl>|<w:p\b[^>]*>[\s\S]*?<\/w:p>|<w:p\b[^>]*\/>/gi;
  const blocks = bodyContent.match(blockRegex) || [];
  const htmlBlocks = [];

  for (const block of blocks) {
    if (/^<w:tbl\b/i.test(block)) {
      const rowMatches = block.match(/<w:tr\b[^>]*>[\s\S]*?<\/w:tr>/gi) || [];
      const rowsHtml = rowMatches
        .map((rowXml, rowIdx) => {
          const cellMatches = rowXml.match(/<w:tc\b[^>]*>[\s\S]*?<\/w:tc>/gi) || [];
          const cellsHtml = cellMatches
            .map((cellXml) => {
              const cellText = extractTextFromWordXml(cellXml).trim();
              const isBold = /<w:b\b[^>]*\/?>/i.test(cellXml);
              const tag = rowIdx === 0 ? 'th' : 'td';
              const inner = isBold && rowIdx > 0
                ? `<strong>${escapeHtml(cellText)}</strong>`
                : escapeHtml(cellText);
              return `<${tag}>${inner}</${tag}>`;
            })
            .join('');
          return `<tr>${cellsHtml}</tr>`;
        })
        .join('');
      if (rowsHtml) {
        htmlBlocks.push(`<table class="word-doc-table">${rowsHtml}</table>`);
      }
      continue;
    }

    // Paragraph <w:p>
    const pStyleMatch = block.match(/<w:pStyle\s+w:val="([^"]+)"/i);
    const pStyle = pStyleMatch ? pStyleMatch[1] : '';
    const isCentered = /<w:jc\s+w:val="center"/i.test(block);
    const isRight = /<w:jc\s+w:val="right"/i.test(block);

    const runMatches = block.match(/<w:r\b[^>]*>[\s\S]*?<\/w:r>/gi) || [];
    let runsHtml = '';
    for (const runXml of runMatches) {
      const texts = (runXml.match(/<w:t\b[^>]*>([\s\S]*?)<\/w:t>/gi) || [])
        .map((tNode) => decodeXmlEntities(tNode.replace(/<[^>]+>/g, '')))
        .join('');
      if (!texts) continue;
      let chunk = escapeHtml(texts);
      if (/<w:b\b[^>]*\/?>/i.test(runXml)) chunk = `<strong>${chunk}</strong>`;
      if (/<w:i\b[^>]*\/?>/i.test(runXml)) chunk = `<em>${chunk}</em>`;
      if (/<w:u\b[^>]*\/?>/i.test(runXml)) chunk = `<u>${chunk}</u>`;
      runsHtml += chunk;
    }

    if (!runsHtml.trim()) continue;

    if (/^Heading1$/i.test(pStyle)) {
      htmlBlocks.push(`<h1 class="word-doc-heading">${runsHtml}</h1>`);
    } else if (/^Heading2$/i.test(pStyle)) {
      htmlBlocks.push(`<h2 class="word-doc-subheading">${runsHtml}</h2>`);
    } else if (isCentered) {
      htmlBlocks.push(`<p class="word-align-center">${runsHtml}</p>`);
    } else if (isRight) {
      htmlBlocks.push(`<p class="word-align-right">${runsHtml}</p>`);
    } else {
      htmlBlocks.push(`<p>${runsHtml}</p>`);
    }
  }

  return sanitizeWordHtml(htmlBlocks.join('\n'));
}

/**
 * Extract readable text from legacy `.doc` (OLE2 / Word 97-2003) or rich text streams.
 * @param {Buffer} buffer
 * @returns {string}
 */
function extractTextFromLegacyDocBuffer(buffer) {
  if (!Buffer.isBuffer(buffer) || buffer.length === 0) return '';

  const utf8Candidate = buffer.toString('utf8');
  if (!utf8Candidate.includes('\u0000')) {
    return utf8Candidate.trim();
  }

  const chunks = [];
  let currentUtf16 = [];
  for (let i = 0; i + 1 < buffer.length; i += 2) {
    const code = buffer.readUInt16LE(i);
    const isPrintable =
      code === 0x09 ||
      code === 0x0a ||
      code === 0x0d ||
      (code >= 0x20 && code <= 0x7e) ||
      (code >= 0x00a0 && code <= 0x024f) ||
      (code >= 0x1e00 && code <= 0x1eff);
    if (isPrintable) {
      currentUtf16.push(String.fromCharCode(code));
    } else {
      if (currentUtf16.length >= 6) {
        chunks.push(currentUtf16.join(''));
      }
      currentUtf16 = [];
    }
  }
  if (currentUtf16.length >= 6) {
    chunks.push(currentUtf16.join(''));
  }

  const combined = chunks
    .map((c) => c.replace(/\r/g, '\n').trim())
    .filter(Boolean)
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();

  return combined || '[Tệp văn bản Word .doc nhị phân — Bấm "Tải tệp về máy" để mở bằng Microsoft Word]';
}

/**
 * Extract human-readable preview text from a document Buffer (`.docx`, `.doc`, `.txt`, etc.)
 * while leaving the original binary buffer untouched.
 * @param {Buffer} fileBuffer
 * @param {string} filename
 * @returns {string}
 */
export function extractDocumentPreviewText(fileBuffer, filename = '') {
  if (!Buffer.isBuffer(fileBuffer) || fileBuffer.length === 0) {
    return '';
  }

  const lowerName = String(filename || '').toLowerCase();
  const isZipMagic =
    fileBuffer.length >= 4 && fileBuffer.readUInt32LE(0) === 0x04034b50;

  if (lowerName.endsWith('.docx') || isZipMagic) {
    const entries = parseZipEntries(fileBuffer);
    const docXmlBuf = entries.get('word/document.xml');
    if (docXmlBuf) {
      const text = extractTextFromWordXml(docXmlBuf.toString('utf8'));
      if (text) return text;
    }
  }

  if (lowerName.endsWith('.doc')) {
    return extractTextFromLegacyDocBuffer(fileBuffer);
  }

  const rawUtf8 = fileBuffer.toString('utf8');
  let nullBytes = 0;
  const checkLen = Math.min(fileBuffer.length, 1024);
  for (let i = 0; i < checkLen; i += 1) {
    if (fileBuffer[i] === 0) nullBytes += 1;
  }
  if (nullBytes > checkLen * 0.1) {
    return `[Tệp nhị phân (${filename || 'document.bin'}, ${fileBuffer.length} bytes) — Bấm "Tải tệp về máy" để mở tệp gốc nguyên vẹn]`;
  }

  return rawUtf8;
}

/**
 * Asynchronously extract both plain text (`extractedText`) and rich formatted HTML (`extractedHtml`)
 * using `mammoth` for `.docx` files (with style mappings for headings, centered headers, tables, bold/italic).
 * @param {Buffer} fileBuffer
 * @param {string} filename
 * @returns {Promise<{ extractedText: string, extractedHtml: string, isWordDoc: boolean }>}
 */
export async function extractDocumentPreviewRich(fileBuffer, filename = '') {
  if (!Buffer.isBuffer(fileBuffer) || fileBuffer.length === 0) {
    return { extractedText: '', extractedHtml: '', isWordDoc: false };
  }

  const lowerName = String(filename || '').toLowerCase();
  const isZipMagic =
    fileBuffer.length >= 4 && fileBuffer.readUInt32LE(0) === 0x04034b50;

  if (lowerName.endsWith('.docx') || isZipMagic) {
    try {
      const [htmlResult, rawTextResult] = await Promise.all([
        mammoth.convertToHtml(
          { buffer: fileBuffer },
          {
            styleMap: [
              "p[style-name='HeaderCenter'] => p.word-align-center:fresh",
              "p[style-name='QuocHieu'] => p.word-quoc-hieu:fresh",
              "p[style-name='TieuNgu'] => p.word-tieu-ngu:fresh",
              "p[style-name='DocTitle'] => h1.word-doc-heading:fresh",
              "p[style-name='SignatureRight'] => p.word-align-right:fresh",
            ],
          }
        ),
        mammoth.extractRawText({ buffer: fileBuffer }),
      ]);

      const entries = parseZipEntries(fileBuffer);
      const docXmlBuf = entries.get('word/document.xml');
      const xmlString = docXmlBuf ? docXmlBuf.toString('utf8') : '';

      const mammothHtml = sanitizeWordHtml(htmlResult?.value || '');
      const xmlRichHtml = xmlString ? convertWordXmlToHtml(xmlString) : '';

      // Prefer the richer HTML representation (preserving centered alignment classes & tables)
      const chosenHtml =
        xmlRichHtml.includes('word-align-center') || xmlRichHtml.includes('word-doc-table')
          ? xmlRichHtml
          : mammothHtml || xmlRichHtml;

      const extractedText =
        (xmlString && extractTextFromWordXml(xmlString)) ||
        (rawTextResult?.value || '').trim();

      return {
        extractedText,
        extractedHtml: chosenHtml,
        isWordDoc: true,
      };
    } catch {
      const fallbackText = extractDocumentPreviewText(fileBuffer, filename);
      return {
        extractedText: fallbackText,
        extractedHtml: convertPlainTextToFormattedHtml(fallbackText),
        isWordDoc: true,
      };
    }
  }

  const extractedText = extractDocumentPreviewText(fileBuffer, filename);
  return {
    extractedText,
    extractedHtml: convertPlainTextToFormattedHtml(extractedText),
    isWordDoc: lowerName.endsWith('.doc'),
  };
}

/**
 * Compute CRC-32 of a Buffer (used for building valid `.docx` ZIP archives).
 * @param {Buffer} buf
 * @returns {number}
 */
function crc32(buf) {
  let crc = 0xffffffff;
  for (let i = 0; i < buf.length; i += 1) {
    crc ^= buf[i];
    for (let j = 0; j < 8; j += 1) {
      crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
    }
  }
  return (crc ^ 0xffffffff) >>> 0;
}

